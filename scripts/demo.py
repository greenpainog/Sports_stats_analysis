"""Run the README's demo questions through POST /ask and print them as Markdown.

    python -m scripts.demo                 # print to the terminal
    python -m scripts.demo > demo.md       # then paste the blocks into README.md

Needs the database in data/ and OPENAI_API_KEY in .env (one LLM call per
question). Only Euroleague and EuroCup questions: the Greek league's source
(esake.gr) allows personal use only, and the README is public.
"""
import json
import sys
from datetime import date

from fastapi.testclient import TestClient

from api.main import app

QUESTIONS = [
    "Compare Panathinaikos and Zalgiris forced turnovers and steals this season",
    "Kendrick Nunn's 3-point percentage in his last 5 games",
    "Olympiacos points per game with and without Fournier this season",
    "Top 5 scorers in the EuroCup this season",
    "Which team allows the fewest points per game this season?",
    "Who will win the Euroleague this season?",
]


MAX_LINES = 8  # a 20-team ranking is cut to its top rows


def _drop_empty(value):
    if isinstance(value, dict):
        return {k: _drop_empty(v) for k, v in value.items() if v not in (None, False, [], {})}
    if isinstance(value, list):
        return [_drop_empty(v) for v in value]
    return value


def _spec(answer):
    """The structured request the LLM produced, without empty fields."""
    spec = answer.get("ranking_spec") or answer.get("spec")
    if not spec:
        return None
    spec = _drop_empty(spec)
    if answer.get("ranking_kind"):
        spec = {"ranking": answer["ranking_kind"], **spec}
    return spec


def to_markdown(answer):
    lines = [f"**\"{answer['question']}\"**", ""]
    spec = _spec(answer)
    if spec:
        lines += ["The LLM's output (validated, then turned into SQL by code):", "",
                  "```json", json.dumps(spec, ensure_ascii=False), "```", ""]
    label = "Answer" if answer["status"] == "answered" else f"Answer ({answer['status']})"
    message = answer["message"].splitlines()
    if len(message) > MAX_LINES:
        message = message[:MAX_LINES] + ["  ..."]
    lines += [f"{label}:", "", "```text", *message, "```", ""]
    return "\n".join(lines)


def main():
    client = TestClient(app)
    print(f"<!-- Generated by scripts/demo.py on {date.today().isoformat()} -->\n")
    for question in QUESTIONS:
        response = client.post("/ask", json={"question": question})
        if response.status_code != 200:
            sys.exit(f"{question!r}: HTTP {response.status_code} {response.text[:200]}")
        print(to_markdown(response.json()))


if __name__ == "__main__":
    main()
